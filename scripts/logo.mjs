// Generates the Nomad logo from exact geometry: three equal arcs (the legs of a ring)
// separated by constant-width gaps, around a settlement dot.
// usage: node scripts/logo.mjs   (writes web/app/icon.svg, web/public/logo*.svg, media/logo-*.svg)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const INK = "#0d0d0d", PAPER = "#f0efec", ACCENT = "#3987e5";

const C = 32, R = 22, r = 13.5, GAP = 5, DOT = 5, SLANT = 28; // 64-unit grid
const GAPS = [-90, 30, 150]; // gap centres, degrees (SVG y points down, so -90 is the top)
// Each gap is a straight cut of constant width GAP, tilted off the radius so the three legs
// read as turning clockwise around the settlement point.
const f = (n) => Number(n.toFixed(3));
const rad = (d) => (d * Math.PI) / 180;
const pol = (deg, p) => [C + p * Math.cos(rad(deg)), C + p * Math.sin(rad(deg))];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const add = (a, b) => [a[0] + b[0], a[1] + b[1]];
const mul = (a, k) => [a[0] * k, a[1] * k];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1];
const unit = (a) => mul(a, 1 / Math.hypot(a[0], a[1]));
function shifted(p1, p2, d, fwd) {
  // the line p1→p2 moved by distance d along its normal, toward fwd when d > 0
  const dir = unit(sub(p2, p1));
  let n = [-dir[1], dir[0]];
  if (dot(n, fwd) < 0) n = mul(n, -1);
  return [add(p1, mul(n, d)), dir];
}
function meet([p, u], [q, v]) {
  const den = u[0] * v[1] - u[1] * v[0];
  const t = ((q[0] - p[0]) * v[1] - (q[1] - p[1]) * v[0]) / den;
  return add(p, mul(u, t));
}
function onCircle([p, u], rho, near) {
  // intersection of the line with the circle of radius rho, nearest to `near`
  const w = sub(p, [C, C]);
  const b = dot(w, u), c = dot(w, w) - rho * rho, s = Math.sqrt(b * b - c);
  const a1 = add(p, mul(u, -b + s)), a2 = add(p, mul(u, -b - s));
  return Math.hypot(...sub(a1, near)) < Math.hypot(...sub(a2, near)) ? a1 : a2;
}
function boundary(g, d) {
  // one side of the slanted cut centred at angle g: a straight line through the band's middle,
  // tilted SLANT degrees off the radius (the swirl), moved d along its normal (d > 0: clockwise)
  const M = pol(g, (R + r) / 2);
  const u = [Math.cos(rad(g)), Math.sin(rad(g))]; // radial, outward
  const t = [-u[1], u[0]]; // tangent, clockwise on screen
  const c = Math.cos(rad(SLANT)), sn = Math.sin(rad(SLANT));
  const v = add(mul(u, c), mul(t, sn)); // the cut's direction
  const L = shifted(add(M, mul(v, -12)), add(M, mul(v, 12)), d, t);
  return { o: onCircle(L, R, add(M, mul(v, 6))), i: onCircle(L, r, add(M, mul(v, -6))) };
}
const P = (q) => `${f(q[0])} ${f(q[1])}`;

export function markPaths() {
  return GAPS.map((g, i) => {
    const s = boundary(g, GAP / 2), e = boundary(GAPS[(i + 1) % 3], -GAP / 2);
    return `M${P(s.o)} A${R} ${R} 0 0 1 ${P(e.o)} L${P(e.i)} A${r} ${r} 0 0 0 ${P(s.i)} Z`;
  });
}

export function markSvg({ ring = PAPER, dot = ACCENT, bg = null, size = 64 } = {}) {
  const back = bg ? `<rect width="64" height="64" rx="14" fill="${bg}"/>` : "";
  const arcs = markPaths().map((d) => `<path d="${d}" fill="${ring}"/>`).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 64 64">${back}${arcs}<circle cx="${C}" cy="${C}" r="${DOT}" fill="${dot}"/></svg>\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = {
    "web/app/icon.svg": markSvg({ bg: INK }),
    "web/public/logo-mark.svg": markSvg(),
    "media/logo-mark-dark.svg": markSvg({ size: 96 }), // for dark backgrounds
    "media/logo-mark-light.svg": markSvg({ ring: INK, size: 96 }), // for light backgrounds
  };
  const arcs = markPaths().map((d) => `      <path d="${d}" fill="currentColor" />`).join("\n");
  out["web/components/LogoMark.tsx"] = `// Generated by scripts/logo.mjs. Do not edit by hand.
export default function LogoMark({ className = "" }: { className?: string }) {
  return (
    <svg viewBox="0 0 64 64" aria-hidden="true" className={className}>
${arcs}
      <circle cx="${C}" cy="${C}" r="${DOT}" fill="${ACCENT}" />
    </svg>
  );
}
`;
  for (const [p, s] of Object.entries(out)) writeFileSync(join(root, p), s);
  console.log(Object.keys(out).join("\n"));
}
